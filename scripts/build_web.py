 ('branches','03 · Make a decision','... score = 85\n?? score >= 80 { ...! "We ARE COKKING" }\n??? score >= 60 { ...! "Keep going" }\n???? { ...! "Try again" }','The first true branch runs. Comparisons produce booleans. Else-if and else complete the choice.','We ARE COKKING'),
