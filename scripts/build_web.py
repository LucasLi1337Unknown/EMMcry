def browser_ir(value):
 if isinstance(value,dict):
  out={k:browser_ir(v) for k,v in value.items()}
  if out.get('tag')=='literal' and type(value.get('value')) is int:
   out['integerText']=str(value['value']);out['value']=None
  if 'loc' in out: out['loc'][0]=pathlib.Path(out['loc'][0]).relative_to(ROOT).as_posix()
  return out
 if isinstance(value,(list,tuple)):return [browser_ir(x) for x in value]
 return value
def build():
 modules={};sources={};hashes={}
 for path in sorted(list((ROOT/'games').glob('*.emm'))+[ROOT/'examples/pokerlib.emm']):
  key=path.relative_to(ROOT).as_posix();source=path.read_text(encoding='utf-8')
  modules[key]=browser_ir(emmc.parse(source,path,'emm'))
  sources[key]={'emm':source,'cry':emmc.translate(source,path,'cry')}
  hashes[key]=hashlib.sha256(source.encode()).hexdigest()
 lessons=[]
 for key,title,source,description,expected in LESSONS:
  file=ROOT/'lessons'/f'{key}.emm';file.parent.mkdir(exist_ok=True)
  file.write_text(source+'\n',encoding='utf-8');cry=emmc.translate(source,file,'cry');file.with_suffix('.cry').write_text(cry,encoding='utf-8')
  lessons.append(dict(id=key,title=title,description=description,expected=expected,emm=source,cry=cry,ir=browser_ir(emmc.parse(source,file,'emm'))))
 payload={'modules':modules,'sources':sources,'hashes':hashes,'lessons':lessons}
 (ROOT/'web/compiled.js').write_text('// Generated by scripts/build_web.py. Do not edit game logic here.\nglobalThis.EMM_PROJECT = '+json.dumps(payload,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
 print(f'Built {len(modules)} EMM modules and {len(lessons)} runnable lessons.')
if __name__=='__main__':build()
